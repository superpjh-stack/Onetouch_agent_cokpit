const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async()=>{
 const browser = await chromium.launch({headless:true});
 const page = await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror', e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8517');
 await page.getByRole('heading',{name:'원터치 AI Agent'}).waitFor();
 await page.screenshot({path:'v2/verification/desktop.png',fullPage:true,animations:'disabled'});
 await page.locator('.document-list button').first().click();
 await page.getByRole('dialog').waitFor();
 assert((await page.locator('.document-content').innerText()).length>50);
 await page.getByRole('button',{name:'닫기',exact:true}).click();
 await page.getByRole('tab',{name:'데이터허브',exact:true}).click();
 await page.locator('.data-preview button').first().click();
 assert((await page.getByRole('dialog').innerText()).includes('QT-260904-001'));
 await page.getByRole('button',{name:'닫기',exact:true}).click();
 await page.getByLabel('질문 대상 견적').selectOption('QT-260904-002');
 await page.locator('.recommend-section button').filter({hasText:'선택 견적의 원가와 BOM을 알려줘'}).click();
 await page.locator('.exchange').waitFor();
 assert((await page.locator('.exchange').innerText()).includes('14,559,200원'));
 await page.locator('.exchange details').first().locator('summary').first().click();
 assert(await page.locator('.exchange .source-detail').count()>0);
 await page.screenshot({path:'v2/verification/evidence.png',fullPage:true,animations:'disabled'});
 await page.getByRole('button',{name:'대화 초기화'}).click();
 await page.locator('.agent-welcome').waitFor();
 await page.locator('.history-list button').first().click();
 await page.locator('.exchange').waitFor();
 await page.getByLabel('질문 대상 견적').selectOption('QT-260904-003');
 await page.locator('.agent-welcome').waitFor();
 assert.equal(await page.locator('.exchange').count(),0);
 await page.getByLabel('에이전트에게 질문').fill('선택 견적의 도면을 알려줘');
 await page.getByRole('button',{name:'질문 보내기'}).click();
 await page.locator('.exchange').waitFor();
 assert((await page.locator('.exchange').innerText()).includes('QT-260904-003'));
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'v2/verification/mobile.png',fullPage:true,animations:'disabled'});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.getByRole('button',{name:'자료',exact:true}).click();
 await page.locator('.library-panel.mobile-open').waitFor();
 await page.getByRole('button',{name:'자료 패널 닫기'}).click();
 await page.getByRole('button',{name:'질문',exact:true}).click();
 await page.locator('.question-panel.mobile-open').waitFor();
 await page.getByRole('tab',{name:'문서·규칙'}).click();
 await page.locator('.recommend-section ol button').first().click();
 await page.waitForFunction(()=>document.querySelectorAll('.exchange').length===2);
 assert.equal(await page.locator('.question-panel.mobile-open').count(),0);
 await page.screenshot({path:'v2/verification/mobile.png',fullPage:true,animations:'disabled'});
 // A late response must never appear under a different quotation context.
 await page.route('**/api/chat', async route=>{
   await new Promise(resolve=>setTimeout(resolve,600));
   await route.fulfill({json:{mode:'demo',text:'STALE_RESPONSE',evidence:[],records:[],context:{quote_id:'QT-260904-003'}}}).catch(()=>{});
 });
 await page.getByLabel('에이전트에게 질문').fill('지연 응답 테스트');
 await page.getByRole('button',{name:'질문 보내기'}).click();
 await page.getByLabel('질문 대상 견적').selectOption('QT-260904-001');
 await page.waitForTimeout(800);
 assert.equal(await page.getByText('STALE_RESPONSE',{exact:true}).count(),0);
 assert.equal(await page.locator('.exchange').count(),0);
 assert(await page.getByLabel('에이전트에게 질문').isEnabled());
 assert.deepEqual(errors,[]);
 console.log('Desktop/mobile: document, raw record, recommendation, history, reset, quote switch, direct question, evidence and panels passed.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
